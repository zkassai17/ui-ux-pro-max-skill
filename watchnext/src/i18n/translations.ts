// App localization. Stage 1 covers the tab bar + Settings across all 5 languages;
// more screens get keys added incrementally. RTL (Hebrew, Arabic) is handled by
// the provider via I18nManager.

export type Lang = "en" | "es" | "fr" | "he" | "ar";

export const LANGUAGES: { code: Lang; label: string; abbr: string; flag: string }[] = [
  { code: "en", label: "English", abbr: "EN", flag: "🇺🇸" },
  { code: "es", label: "Español", abbr: "ES", flag: "🇪🇸" },
  { code: "fr", label: "Français", abbr: "FR", flag: "🇫🇷" },
  { code: "he", label: "עברית", abbr: "HE", flag: "🇮🇱" },
  { code: "ar", label: "العربية", abbr: "AR", flag: "🇸🇦" },
];

const RTL_LANGS: Lang[] = ["he", "ar"];

export function isRtlLang(lang: Lang): boolean {
  return RTL_LANGS.includes(lang);
}

const SUPPORTED = LANGUAGES.map((l) => l.code) as string[];

// First device language we support (e.g. phone set to French -> "fr"), else English.
// Used to pick a sensible default before the user has chosen one in Settings.
export function pickLanguage(deviceCodes: (string | null | undefined)[]): Lang {
  for (const c of deviceCodes) {
    if (c && SUPPORTED.includes(c)) return c as Lang;
  }
  return "en";
}

